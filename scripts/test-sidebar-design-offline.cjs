const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const assert = require('node:assert/strict');
const file = path.join(__dirname, '../app/components/Sidebar.tsx');
const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2020 } }).outputText;
const result = {};
vm.runInNewContext(code, { exports: result, require: name => {
  if (name === 'react/jsx-runtime') return require(name);
  if (name === 'next/link') return { default: ({ children, ...props }) => React.createElement('a', props, children) };
  if (name === 'next/navigation') return { usePathname: () => '/submissions', useRouter: () => ({ push() {} }) };
  if (name === 'firebase/auth') return { signOut() {} };
  if (name === 'lucide-react') return require(name);
  if (name === '@/lib/firebase') return { auth: {} };
  if (name === '@/lib/useCurrentUser') return { useCurrentUser: () => ({ user: { role: 'admin', name: 'Synthetic user' } }) };
  if (name === '@/lib/usePermissions') return { usePermissions: () => ({ permissions: {} }) };
  if (name === '@/lib/userAccounts') return { isClientAccount: () => false };
  if (name === '@/lib/can') return { can: () => false };
  if (name === '@/lib/useClientBrand') return { useClientBrand: () => ({}) };
  if (name === '@/lib/clientI18n') return { useClientI18n: () => ({ t: text => text, dir: 'ltr', language: 'en' }) };
  throw Error('Blocked: ' + name);
} });
const expanded = renderToStaticMarkup(React.createElement(result.default, { onToggle() {} }));
const collapsed = renderToStaticMarkup(React.createElement(result.default, { collapsed: true, onToggle() {} }));
assert(expanded.includes('aria-label="Collapse sidebar"'));
assert(collapsed.includes('aria-label="Expand sidebar"'));
assert(collapsed.includes('title="Submissions" aria-label="Submissions" aria-current="page"'));
assert(collapsed.includes('aria-label="Logout"'));
const links = html => [...html.matchAll(/href="([^"]+)"/g)].map(match => match[1]).sort();
assert.deepEqual(links(expanded), links(collapsed));
assert(!collapsed.includes('Synthetic user'));
console.log('PASS: actual Sidebar renders both modes; navigation destinations preserved, active link, accessible labels, in-sidebar controls, logout. Synthetic only.');
